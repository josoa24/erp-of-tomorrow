SET ROLE vente_svc;

CREATE TABLE IF NOT EXISTS vente.sale_payments (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    sale_id bigint NOT NULL,
    amount numeric(14,2) NOT NULL,
    method varchar(20) NOT NULL,
    paid_at timestamp(6) with time zone NOT NULL,
    reference varchar(64),
    recorded_by bigint,
    CONSTRAINT sale_payments_pkey PRIMARY KEY (id)
);

ALTER TABLE vente.sale_payments DROP CONSTRAINT IF EXISTS fk_sale_payments_sale;

ALTER TABLE vente.sale_payments ADD CONSTRAINT fk_sale_payments_sale
    FOREIGN KEY (sale_id) REFERENCES vente.sales (id);

ALTER TABLE vente.sale_payments DROP CONSTRAINT IF EXISTS ck_sale_payments_amount_positive;

ALTER TABLE vente.sale_payments ADD CONSTRAINT ck_sale_payments_amount_positive CHECK (amount > 0);

ALTER TABLE vente.sale_payments DROP CONSTRAINT IF EXISTS sale_payments_method_check;

ALTER TABLE vente.sale_payments ADD CONSTRAINT sale_payments_method_check
    CHECK (method IN ('CASH', 'MVOLA', 'ORANGE_MONEY', 'AIRTEL_MONEY', 'CREDIT'));

CREATE INDEX IF NOT EXISTS idx_sale_payments_sale ON vente.sale_payments (sale_id);

DO $$
BEGIN
    IF to_regclass('vente.sale_cancellations') IS NULL THEN
        INSERT INTO vente.sale_payments (sale_id, amount, method, paid_at)
        SELECT s.id, s.total_amount, 'CASH', coalesce(s.validated_at, s.created_at)
        FROM vente.sales s
        WHERE s.status = 'VALIDATED'
          AND s.payment_method IS NULL
          AND s.total_amount > 0
          AND NOT EXISTS (SELECT 1 FROM vente.sale_payments p WHERE p.sale_id = s.id);
    ELSE
        INSERT INTO vente.sale_payments (sale_id, amount, method, paid_at)
        SELECT s.id, s.total_amount, 'CASH', coalesce(s.validated_at, s.created_at)
        FROM vente.sales s
        WHERE s.status = 'VALIDATED'
          AND s.payment_method IS NULL
          AND s.total_amount > 0
          AND NOT EXISTS (SELECT 1 FROM vente.sale_payments p WHERE p.sale_id = s.id)
          AND NOT EXISTS (SELECT 1 FROM vente.sale_cancellations c WHERE c.sale_id = s.id);
    END IF;
END
$$;

RESET ROLE;
