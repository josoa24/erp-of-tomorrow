SET ROLE module_svc;

CREATE TABLE IF NOT EXISTS module.module_definition (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    slug varchar(60) NOT NULL,
    name varchar(40) NOT NULL,
    icon varchar(40) NOT NULL,
    description varchar(280),
    created_by varchar(255) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT module_definition_pkey PRIMARY KEY (id),
    CONSTRAINT uk_module_definition_slug UNIQUE (slug)
);

CREATE TABLE IF NOT EXISTS module.module_column (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    definition_id bigint NOT NULL,
    position integer NOT NULL,
    "key" varchar(40) NOT NULL,
    label varchar(60) NOT NULL,
    type varchar(20) NOT NULL,
    required boolean NOT NULL,
    choices text,
    reference_target varchar(20),
    CONSTRAINT module_column_pkey PRIMARY KEY (id),
    CONSTRAINT uk_module_column_definition_key UNIQUE (definition_id, "key"),
    CONSTRAINT fk_module_column_definition FOREIGN KEY (definition_id)
        REFERENCES module.module_definition (id) ON DELETE CASCADE,
    CONSTRAINT module_column_type_check
        CHECK (type IN ('TEXT', 'NUMBER', 'MONEY', 'DATE', 'TIME', 'DATETIME', 'CHOICE', 'REFERENCE')),
    CONSTRAINT module_column_reference_target_check
        CHECK (reference_target IN ('CUSTOMER', 'SALE', 'EMPLOYEE', 'PRODUCT', 'SUPPLIER'))
);

CREATE TABLE IF NOT EXISTS module.module_status (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    definition_id bigint NOT NULL,
    position integer NOT NULL,
    "key" varchar(40) NOT NULL,
    label varchar(60) NOT NULL,
    tone varchar(20) NOT NULL,
    "final" boolean NOT NULL,
    CONSTRAINT module_status_pkey PRIMARY KEY (id),
    CONSTRAINT uk_module_status_definition_key UNIQUE (definition_id, "key"),
    CONSTRAINT fk_module_status_definition FOREIGN KEY (definition_id)
        REFERENCES module.module_definition (id) ON DELETE CASCADE,
    CONSTRAINT module_status_tone_check CHECK (tone IN ('SUCCESS', 'WARNING', 'CRITICAL', 'INFO', 'NEUTRAL'))
);

CREATE TABLE IF NOT EXISTS module.module_indicator (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    definition_id bigint NOT NULL,
    position integer NOT NULL,
    "key" varchar(40) NOT NULL,
    label varchar(60) NOT NULL,
    icon varchar(40) NOT NULL,
    kind varchar(20) NOT NULL,
    statuses text,
    column_key varchar(40),
    today_column_key varchar(40),
    detail_column_key varchar(40),
    CONSTRAINT module_indicator_pkey PRIMARY KEY (id),
    CONSTRAINT fk_module_indicator_definition FOREIGN KEY (definition_id)
        REFERENCES module.module_definition (id) ON DELETE CASCADE,
    CONSTRAINT module_indicator_kind_check CHECK (kind IN ('COUNT', 'SUM', 'RATIO_TODAY'))
);

CREATE TABLE IF NOT EXISTS module.module_record (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    definition_id bigint NOT NULL,
    "values" jsonb NOT NULL,
    status varchar(40) NOT NULL,
    created_by varchar(255) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT module_record_pkey PRIMARY KEY (id),
    CONSTRAINT fk_module_record_definition FOREIGN KEY (definition_id)
        REFERENCES module.module_definition (id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_module_record_definition_status ON module.module_record (definition_id, status);

CREATE TABLE IF NOT EXISTS module.adaptation_activation (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    module_key varchar(60) NOT NULL,
    adaptation_key varchar(80) NOT NULL,
    activated_by varchar(255) NOT NULL,
    activated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT adaptation_activation_pkey PRIMARY KEY (id),
    CONSTRAINT uk_adaptation_activation_key UNIQUE (adaptation_key)
);

RESET ROLE;
