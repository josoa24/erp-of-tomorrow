SET ROLE rh_svc;

DO $$
BEGIN
    IF to_regclass('rh.employees') IS NULL THEN
        RETURN;
    END IF;

    CREATE TABLE IF NOT EXISTS rh.salary_advances (
        id bigint GENERATED BY DEFAULT AS IDENTITY,
        employee_id bigint NOT NULL,
        month date NOT NULL,
        amount numeric(14,2) NOT NULL,
        reason varchar(500),
        status varchar(16) NOT NULL,
        created_at timestamp(6) with time zone NOT NULL,
        decided_at timestamp(6) with time zone,
        decided_by bigint,
        CONSTRAINT salary_advances_pkey PRIMARY KEY (id)
    );

    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conrelid = 'rh.salary_advances'::regclass AND conname = 'fk_salary_advances_employee') THEN
        ALTER TABLE rh.salary_advances ADD CONSTRAINT fk_salary_advances_employee
            FOREIGN KEY (employee_id) REFERENCES rh.employees (id);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conrelid = 'rh.salary_advances'::regclass AND conname = 'salary_advances_amount_check') THEN
        ALTER TABLE rh.salary_advances ADD CONSTRAINT salary_advances_amount_check CHECK (amount > 0);
    END IF;

    ALTER TABLE rh.salary_advances DROP CONSTRAINT IF EXISTS salary_advances_status_check;
    ALTER TABLE rh.salary_advances ADD CONSTRAINT salary_advances_status_check
        CHECK (status IN ('DRAFT', 'VALIDATED', 'REJECTED'));

    CREATE INDEX IF NOT EXISTS idx_salary_advances_employee_month ON rh.salary_advances (employee_id, month);
END
$$;

RESET ROLE;
