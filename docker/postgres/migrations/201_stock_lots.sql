SET ROLE stock_svc;

DO $$
BEGIN
    IF to_regclass('stock.products') IS NULL OR to_regclass('stock.stock_movements') IS NULL THEN
        RETURN;
    END IF;

    CREATE TABLE IF NOT EXISTS stock.stock_lots (
        id bigint GENERATED BY DEFAULT AS IDENTITY,
        product_id bigint NOT NULL,
        movement_id bigint NOT NULL,
        lot_number varchar(64) NOT NULL,
        expiry_date date NOT NULL,
        quantity integer NOT NULL,
        received_at timestamp(6) with time zone NOT NULL,
        CONSTRAINT stock_lots_pkey PRIMARY KEY (id)
    );

    CREATE TABLE IF NOT EXISTS stock.stock_lot_allocations (
        id bigint GENERATED BY DEFAULT AS IDENTITY,
        lot_id bigint NOT NULL,
        movement_id bigint NOT NULL,
        quantity integer NOT NULL,
        CONSTRAINT stock_lot_allocations_pkey PRIMARY KEY (id)
    );

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_stock_lots_product'
                   AND conrelid = 'stock.stock_lots'::regclass) THEN
        ALTER TABLE stock.stock_lots ADD CONSTRAINT fk_stock_lots_product
            FOREIGN KEY (product_id) REFERENCES stock.products (id);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_stock_lots_movement'
                   AND conrelid = 'stock.stock_lots'::regclass) THEN
        ALTER TABLE stock.stock_lots ADD CONSTRAINT fk_stock_lots_movement
            FOREIGN KEY (movement_id) REFERENCES stock.stock_movements (id);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uk_stock_lots_movement'
                   AND conrelid = 'stock.stock_lots'::regclass) THEN
        ALTER TABLE stock.stock_lots ADD CONSTRAINT uk_stock_lots_movement UNIQUE (movement_id);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uk_stock_lots_product_lot'
                   AND conrelid = 'stock.stock_lots'::regclass) THEN
        ALTER TABLE stock.stock_lots ADD CONSTRAINT uk_stock_lots_product_lot UNIQUE (product_id, lot_number);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_stock_lots_quantity_positive'
                   AND conrelid = 'stock.stock_lots'::regclass) THEN
        ALTER TABLE stock.stock_lots ADD CONSTRAINT ck_stock_lots_quantity_positive CHECK (quantity > 0);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_stock_lot_allocations_lot'
                   AND conrelid = 'stock.stock_lot_allocations'::regclass) THEN
        ALTER TABLE stock.stock_lot_allocations ADD CONSTRAINT fk_stock_lot_allocations_lot
            FOREIGN KEY (lot_id) REFERENCES stock.stock_lots (id);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_stock_lot_allocations_movement'
                   AND conrelid = 'stock.stock_lot_allocations'::regclass) THEN
        ALTER TABLE stock.stock_lot_allocations ADD CONSTRAINT fk_stock_lot_allocations_movement
            FOREIGN KEY (movement_id) REFERENCES stock.stock_movements (id);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_stock_lot_allocations_quantity_positive'
                   AND conrelid = 'stock.stock_lot_allocations'::regclass) THEN
        ALTER TABLE stock.stock_lot_allocations ADD CONSTRAINT ck_stock_lot_allocations_quantity_positive
            CHECK (quantity > 0);
    END IF;

    CREATE INDEX IF NOT EXISTS ix_stock_lots_product ON stock.stock_lots (product_id);
    CREATE INDEX IF NOT EXISTS ix_stock_lot_allocations_lot ON stock.stock_lot_allocations (lot_id);
    CREATE INDEX IF NOT EXISTS ix_stock_lot_allocations_movement ON stock.stock_lot_allocations (movement_id);
END $$;

RESET ROLE;
